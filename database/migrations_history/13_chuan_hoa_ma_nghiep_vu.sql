/* Phiên 2 - Chuẩn hóa mã nghiệp vụ.
   Giữ nguyên toàn bộ IDENTITY PK/FK; chỉ thêm mã hiển thị có tiền tố.
   Script có thể chạy lặp lại, không xóa dữ liệu. Chạy sau migration 12. */
